/** 阶段二统一右工作区回归：复用临时服务、假帮手与现有面板调用方。 */
import assert from "node:assert/strict";
import { createServer } from "node:net";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright-core";
import { makeTempRun, startTempServer, browserEnv, cleanupTempRun } from "./fixtures/temp-server.mjs";
import { seedSubagent } from "./fixtures/seed-subagent.mjs";
import { artifactDir } from "./fixtures/artifacts.mjs";
import { uploadFixture } from "./fixtures/upload.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const run = makeTempRun("pia-right-workspace-");
const port = await new Promise((resolve) => { const s = createServer().listen(0, "127.0.0.1", () => { const p = s.address().port; s.close(() => resolve(p)); }); });
const base = `http://127.0.0.1:${port}`;
const server = startTempServer({ root, port, run, log: process.env.WORK_DEBUG ? (d) => process.stdout.write(d) : undefined });
const out = process.env.SHOT_DIR ?? join(artifactDir("screenshots"), "right-workspace");
mkdirSync(out, { recursive: true });
const j = async (path, method = "GET", body) => { const r = await fetch(base + path, { method, headers: { "content-type": "application/json" }, body: body === undefined ? undefined : JSON.stringify(body) }); const text = await r.text(); let data = {}; try { data = JSON.parse(text); } catch {} if (!r.ok) throw new Error(`${method} ${path} ${r.status}: ${text.slice(0, 300)}`); return data; };
const wait = async (fn, ms = 30000, label = "condition") => { const end = Date.now() + ms; while (Date.now() < end) { if (await fn().catch(() => false)) return; await new Promise((r) => setTimeout(r, 120)); } throw new Error(`${label} timed out`); };
const near = (a, b, n = 3) => Math.abs(a - b) <= n;
let browser;
try {
	await wait(async () => (await fetch(base + "/api/system")).ok, 30000, "server");
	await j("/api/settings", "PUT", { onboarded: true });
	await j("/api/models/default", "PUT", { provider: "mock", model: "echo" }).catch(() => {});
	const agent = await j("/api/agents", "POST", { name: "工作区助理", model: { provider: "mock", id: "echo" } });
	const member = await j("/api/agents", "POST", { name: "工作区成员", model: { provider: "mock", id: "echo" } });
	const room = await j("/api/rooms", "POST", { name: "工作区群", memberIds: [agent.id, member.id], managerId: agent.id });
	const conv = (await j(`/api/agents/${agent.id}/conversations`)).current;
	seedSubagent(run, { id: "workspace-helper", agentId: agent.id, conversationId: conv, provider: "mock", modelId: "echo", task: "统一工作区测试帮手", status: "done" });
	await j(`/api/rooms/${room.id}/work-items`, "POST", { title: "统一工作区测试任务", requirement: "验证任务详情保留", ownerAgentId: member.id, start: false });
	browser = await chromium.launch({ executablePath: process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true, env: browserEnv(run) });
	const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: "zh-CN" });
	page.setDefaultTimeout(15000);
	const errors = [];
	page.on("pageerror", (e) => errors.push(e.message));
	const ws = page.getByTestId("right-workspace");
	const mode = () => ws.getAttribute("data-mode");
	const visibleEntry = () => page.locator("[data-workspace-key]:not([hidden])");
	const openAndCheck = async (button, panel) => { await page.getByTestId(button).click(); await page.getByTestId(panel).waitFor(); assert.equal(await mode(), "docked"); assert.equal(await page.locator("[data-testid=right-workspace] [data-workspace-key]:visible").count(), 1, "同一时间只显示一个内容实例"); };

	await page.goto(`${base}/?agent=${agent.id}`);
	await page.getByTestId("subagent-tasks").waitFor();
	await openAndCheck("subagent-tasks", "task-overview");
	assert.equal(await page.getByTestId("task-overview").getByTestId("subagent-row").count(), 1);
	await page.getByTestId("workspace-expand").click();
	assert.equal(await mode(), "expanded");
	const expandedNode = await visibleEntry().elementHandle();
	await page.getByTestId("workspace-restore").click();
	assert.equal(await mode(), "docked");
	assert.equal(await expandedNode.evaluate((el) => el === document.querySelector('[data-workspace-key]:not([hidden])')), true, "放大/恢复不更换内容宿主");
	await page.getByTestId("workspace-collapse").click();
	assert.equal(await ws.getAttribute("data-collapsed"), "1", "收起只隐藏，不关闭标签");
	await page.getByTestId("workspace-reopen").click();
	assert.equal(await mode(), "docked");
	await page.getByTestId("workspace-close-tab").click();
	await ws.waitFor({ state: "hidden" });

	await page.getByTestId("inbox-button").click();
	await page.getByTestId("inbox").waitFor();
	assert.equal(await mode(), "docked");
	await page.getByTestId("workspace-collapse").click();
	await page.getByTestId("workspace-reopen").click();
	assert.equal(await page.getByTestId("inbox").count(), 1, "提醒内容复用同一标签");
	await page.getByTestId("workspace-close-tab").click();

	await page.goto(`${base}/?room=${room.id}`);
	await openAndCheck("room-work-items", "work-items-overview");
	await page.getByTestId("work-item-row").first().click();
	await page.getByTestId("work-detail").waitFor();
	assert.match(await page.getByTestId("work-detail-title").innerText(), /统一工作区测试任务/);
	const attachment = await uploadFixture(base, `/api/rooms/${room.id}/upload`, "工作区任务说明与文件切换保留验证.md", Buffer.from("# 文件切换证据\n\n" + "这是临时测试的真实预览内容。\n\n".repeat(120)));
	await j(`/api/rooms/${room.id}/messages`, "POST", { text: "工作区文件验证", mentions: [], attachments: [attachment.fileId] });
	// Exercise the real room attachment entry, not a debug opening API.
	await page.getByTestId("work-detail-back").click();
	await page.getByTestId("workspace-collapse").click();
	await page.reload();
	await page.getByTestId("room-work-items").click();
	await page.getByTestId("work-item-row").first().click();
	await page.getByTestId("work-detail").waitFor();
	await page.getByRole("button", { name: `预览 ${attachment.name}`, exact: true }).click();
	await page.getByTestId("file-preview-markdown").waitFor();
	assert.match(await page.getByTestId("file-preview-markdown").innerText(), /文件切换证据/);
	const tabs = page.getByTestId("workspace-tabs");
	const taskTab = tabs.getByRole("tab", { name: "任务详情", exact: true });
	await taskTab.click();
	assert.match(await page.getByTestId("work-detail-title").innerText(), /统一工作区测试任务/);
	await tabs.getByRole("tab", { name: attachment.name, exact: true }).click();
	assert.equal(await page.getByTestId("file-preview").count(), 1);
	await page.getByTestId("workspace-close-tab").click();
	assert.equal(await page.getByTestId("work-detail").isVisible(), true);
	await page.getByTestId("workspace-close-tab").click();

	await page.getByTestId("workspace-browser-open").click();
	await page.getByTestId("workspace-browser-empty").waitFor();
	assert.match(await page.getByTestId("workspace-browser-empty").innerText(), /还没有打开网页/);
	assert.equal(await page.getByTestId("workspace-browser").locator("input, button, iframe, canvas:visible").count(), 1, "未打开网页只显示群成员选择器，不显示假地址栏或操作控件");
	await page.getByTestId("workspace-collapse").click();
	await page.setViewportSize({ width: 390, height: 844 });
	await page.getByTestId("workspace-reopen").click();
	assert.equal(await mode(), "mobile");
	await page.getByTestId("workspace-back-chat").click();
	assert.equal(await ws.getAttribute("data-collapsed"), "1");
	assert.deepEqual(errors, []);
	console.log("right-workspace-ui 全部通过");
} finally {
	await browser?.close();
	await server.stop();
	cleanupTempRun(run);
}
