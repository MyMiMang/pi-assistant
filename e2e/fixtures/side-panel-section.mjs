/** 文件预览既有fixture上的统一工作区回归；不新建另一套文件服务。 */
export async function runSidePanelSection({ browser, base, installRoutes, check, OUT, join }) {
	const state = { fileHits: [], remoteHits: [] };
	const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "zh-CN", acceptDownloads: true });
	await installRoutes(ctx, state);
	await ctx.addInitScript(() => { if (!localStorage.getItem("pia.skin")) { localStorage.setItem("pia.skin", "noir"); localStorage.setItem("pia.theme", "dark"); } });
	const page = await ctx.newPage();
	const errors = [];
	page.on("pageerror", (e) => errors.push(String(e)));
	try {
		await page.goto(`${base}/?agent=a1`);
		const open = (name) => page.getByRole("button", { name: `预览 ${name}`, exact: true }).click();
		const workspace = page.getByTestId("right-workspace");
		const current = () => page.locator('[data-workspace-key]:not([hidden])');
		const box = () => workspace.boundingBox();
		await page.getByRole("button", { name: "信息面板", exact: true }).click();
		await page.getByTestId("info-tabs").waitFor();
		await open("voice-input-feasibility.md");
		await page.getByTestId("file-preview-markdown").waitFor();
		const pb = await box(), cb = await page.getByTestId("main-conversation").boundingBox();
		check("[工作区] 停靠且聊天至少520宽", pb && cb && cb.width >= 520 && near(pb.x, cb.x + cb.width, 2) && near(pb.x + pb.width, 1440, 2));
		check("[工作区] 信息面板让位", !(await page.getByTestId("info-tabs").isVisible()));
		check("[工作区] 默认宽560", near(pb.width, 560, 2));
		const rz = await page.getByRole("separator", { name: "调整侧栏宽度" }).boundingBox();
		await page.mouse.move(rz.x + rz.width / 2, 400); await page.mouse.down();
		await page.mouse.move(rz.x - 60, 400, { steps: 6 }); await page.mouse.up();
		check("[工作区] 拖宽且偏好保存", (await box()).width > 610 && (await page.evaluate(() => JSON.parse(localStorage.getItem("pia.layout")).previewW)) > 610);
		await page.getByRole("separator", { name: "调整侧栏宽度" }).dblclick();
		check("[工作区] 双击恢复宽度", near((await box()).width, 560, 2));
		await page.getByTestId("md-mode-source").click();
		const original = await current().elementHandle();
		await open("data.csv");
		await page.getByTestId("file-preview-csv").waitFor();
		check("[工作区] 两文件同时保留", await page.getByTestId("file-preview").count() === 2);
		await open("voice-input-feasibility.md");
		check("[工作区] 去重且模式保留", await page.getByTestId("file-preview").count() === 2 && await current().getByTestId("file-preview-code").isVisible());
		await page.getByTestId("workspace-expand").click();
		check("[工作区] 放大不重挂", await original.evaluate((el) => el === document.querySelector('[data-workspace-key]:not([hidden])')));
		await page.getByTestId("workspace-restore").click();
		await page.getByTestId("workspace-collapse").click();
		await workspace.waitFor({ state: "hidden" });
		check("[工作区] 收起保留实例并恢复信息面板", await page.getByTestId("file-preview").count() === 2 && await page.getByTestId("info-tabs").isVisible());
		await page.getByTestId("workspace-reopen").click();
		check("[工作区] 恢复不重挂", await original.evaluate((el) => el === document.querySelector('[data-workspace-key]:not([hidden])')));
		await page.screenshot({ path: join(OUT, "side-panel-noir-dark.png") });
		await page.getByTestId("workspace-close-tab").click();
		check("[工作区] 关闭当前项只释放该文件", await page.getByTestId("file-preview").count() === 1 && await current().getByTestId("file-preview-csv").isVisible());
		await page.getByTestId("workspace-close-tab").click();
		await workspace.waitFor({ state: "hidden" });
		await open("config.json");
		await page.locator("textarea").first().fill("你好");
		await page.locator("textarea").first().focus(); await page.keyboard.press("Escape");
		check("[工作区] 输入框Esc不收起", await workspace.isVisible());
		await current().getByTestId("file-preview-name").click(); await page.keyboard.press("Escape");
		await workspace.waitFor({ state: "hidden" });
		await page.getByTestId("conv-menu").click(); await page.getByText("第二段对话", { exact: true }).click();
		await page.getByTestId("file-preview").waitFor({ state: "detached" });
		check("[工作区] 收起后切对话仍清理", await page.getByTestId("workspace-reopen").isDisabled());
		await page.evaluate(() => { localStorage.setItem("pia.skin", "glass"); localStorage.setItem("pia.theme", "light"); });
		await page.reload();
		await open("voice-input-feasibility.md"); await page.getByTestId("file-preview-markdown").waitFor();
		await page.screenshot({ path: join(OUT, "side-panel-glass-light.png") });
		await page.setViewportSize({ width: 1100, height: 800 });
		await page.waitForFunction(() => document.querySelector('[data-testid=right-workspace]')?.getAttribute("data-mode") === "mobile");
		check("[工作区] 临界宽度单内容页", (await box()).width === 1100 && await page.getByTestId("workspace-back-chat").isVisible());
		await page.getByTestId("workspace-back-chat").click(); await workspace.waitFor({ state: "hidden" });
		check("[工作区] 返回聊天保留文件", await page.getByTestId("file-preview").count() === 1);
		check("[工作区] 控制台无报错", errors.length === 0, errors.join(" | "));
	} finally { await ctx.close(); }
}
const near = (a, b, tolerance = 2) => Math.abs(a - b) <= tolerance;
